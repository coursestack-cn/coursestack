import { readFile } from 'node:fs/promises';
import { generateSQLiteDrizzleJson, generateSQLiteMigration } from 'drizzle-kit/api';
import * as schema from '../../src/db/schema.ts';
import { migrationsDirectory, splitMigration } from './migrations.mjs';

export const baselineName = '0000_schema.sql';
export const baselineFile = new URL(baselineName, migrationsDirectory);

export async function generateSchema() {
    const empty = await generateSQLiteDrizzleJson({});
    const current = await generateSQLiteDrizzleJson(schema);
    const tables = await generateSQLiteMigration(empty, current);
    const rules = splitMigration(await readFile(new URL('../../src/db/rules.sql', import.meta.url), 'utf8'));
    return '-- Generated by pnpm db:generate for an empty database.\n'
        + '-- Edit src/db/schema.ts and src/db/rules.sql, then regenerate.\n'
        + [...tables, ...rules].map(sql => sql.trim()).join('\n--> statement-breakpoint\n');
}